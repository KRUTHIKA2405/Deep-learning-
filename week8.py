# ==========================================
# Practical 8: Stock Market Prediction using LSTM
# Dataset: NASDAQ100 Daily Stock Data (2000-2026)
# ==========================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Input
from tensorflow.keras.optimizers import Adam


# 1. Load Kaggle Dataset
data = pd.read_csv("NASDAQ100_Historical_Data.csv")

print(data.head())
print(data.columns)


# 2. Select One Stock
# Change AAPL to any ticker available in your dataset
data = data[data["Ticker"] == "AAPL"].copy()

data["Date"] = pd.to_datetime(data["Date"])
data = data.sort_values("Date")


# 3. Select Closing Price
prices = data[["Close"]].values


# 4. Normalize Data
scaler = MinMaxScaler()

prices = scaler.fit_transform(prices)


# 5. Create 60-Day Sequences
X, y = [], []
days = 60

for i in range(days, len(prices)):
    X.append(prices[i-days:i])
    y.append(prices[i])

X = np.array(X)
y = np.array(y)


# 6. Train-Test Split
split = int(0.8 * len(X))

X_train = X[:split]
X_test = X[split:]

y_train = y[:split]
y_test = y[split:]


# 7. Build LSTM Model
model = Sequential([
    Input(shape=(60, 1)),
    LSTM(50, return_sequences=True),
    LSTM(50),
    Dense(1)
])


# 8. Compile
model.compile(
    optimizer=Adam(0.001),
    loss="mse"
)


# 9. Train
model.fit(
    X_train,
    y_train,
    epochs=20,
    batch_size=32,
    validation_split=0.1,
    verbose=1
)


# 10. Predict
pred = model.predict(X_test, verbose=0)

pred = scaler.inverse_transform(pred)
actual = scaler.inverse_transform(y_test)


# 11. Evaluate
mae = mean_absolute_error(actual, pred)
mse = mean_squared_error(actual, pred)
rmse = np.sqrt(mse)

print("\nMAE :", mae)
print("MSE :", mse)
print("RMSE:", rmse)


# 12. Actual vs Predicted
plt.figure(figsize=(12, 5))

plt.plot(actual, label="Actual")
plt.plot(pred, label="Predicted")

plt.title("AAPL Actual vs Predicted Closing Price")
plt.xlabel("Trading Days")
plt.ylabel("Closing Price")
plt.legend()
plt.grid(True)
plt.show()